#!/bin/sh
set -eu

usage() {
    printf 'Usage: sh %s <version> | --check [tag]\n' "$0" >&2
    exit 1
}

sdk_dir=$(CDPATH= cd "$(dirname "$0")" && pwd)
version_file="$sdk_dir/VERSION"
package_file="$sdk_dir/saasus-sdk-csharp.csproj"
source_file="$sdk_dir/Properties/SdkVersion.cs"
mode=${1:-}

read_package_version() {
    sed -n 's|^    <Version>\([^<]*\)</Version>[[:space:]]*$|\1|p' "$package_file"
}

render_source() {
    printf '%s\n' '// Code generated by update-version.sh. Do not edit.' '' \
        'namespace SaaSus' '{' '    internal static class SdkVersion' '    {' \
        "        internal const string Value = \"$version\";" '    }' '}'
}

if [ "$mode" = "--check" ]; then
    shift
    [ "$#" -le 1 ] || usage
    version=$(read_package_version)
    if [ "$#" -eq 1 ] && [ "${1#v}" != "$version" ]; then
        printf 'Release tag %s does not match saasus-sdk-csharp.csproj (%s)\n' "$1" "$version" >&2
        exit 1
    fi
else
    [ "$#" -eq 1 ] || usage
    version=${1#v}
fi

case "$version" in
    *[!0-9A-Za-z.+-]*) printf 'Invalid SDK version\n' >&2; exit 1 ;;
esac
if ! printf '%s\n' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+[0-9A-Za-z.-]*(\+[0-9A-Za-z.-]+)?$'; then
    printf 'Invalid SDK version\n' >&2
    exit 1
fi

if [ "$mode" = "--check" ]; then
    if ! printf '%s\n' "$version" | cmp -s "$version_file" - || ! render_source | cmp -s "$source_file" -; then
        printf 'VERSION or C# constant does not match saasus-sdk-csharp.csproj (%s)\n' "$version" >&2
        exit 1
    fi
else
    current_version=$(read_package_version)
    case "$current_version" in
        ''|*[!0-9A-Za-z.+-]*) printf 'Expected one package version in saasus-sdk-csharp.csproj\n' >&2; exit 1 ;;
    esac
    if [ "$current_version" != "$version" ]; then
        temp_file=$(mktemp "$package_file.tmp.XXXXXX")
        trap 'rm -f "$temp_file"' EXIT
        sed "s|^\(    <Version>\)[^<]*|\\1$version|" "$package_file" > "$temp_file"
        mv "$temp_file" "$package_file"
    fi
    printf '%s\n' "$version" > "$version_file"
    render_source > "$source_file"
fi
